'use client';
import { useEffect, useMemo, useState } from 'react';
import { supabase } from '../lib_supabase';
import { AsyncButton, Brand, Icon, money } from '../ui';
import { PHOTO_CHECKLISTS, serviceLabel } from '../lib/domain';
import { SECTION_TEMPLATES } from '../lib/section-templates';
import {
  LABOR_TIERS,
  laborUnitFromTier,
  priceSectionedEstimate,
  sectionCustomerProjection,
  tierRate,
  type EstimateSection,
  type LaborTierKey,
  type SectionLine,
} from '@yavamo/core';

/**
 * Billdr-style sectioned estimate generator — PREVIEW (branch-only).
 *
 * Left: collapsible sections of Task | Quantity | Material | Labor |
 * Markup | Total lines, all inline-editable, priced by @yavamo/core
 * section math. Right rail: assistant chat with a real step trace
 * (context → catalog match → lookup flags → summary) plus Summary /
 * Job / Files tabs.
 *
 * The draft is generated by POST /api/estimate-sections (catalog-first,
 * deterministic matcher; misses become flagged placeholders — prices are
 * never invented). Every line stays DRAFT behind the office review gate.
 * PREVIEW SAFETY: nothing on this page writes to the shared production
 * database — saving is disabled until Lavie approves the merge.
 */

interface ChatMsg { role: 'user' | 'assistant'; text: string }
interface TraceItem { label: string; detail: string; ok: boolean }
interface TracePhase { id: string; label: string; ms: number; items: TraceItem[] }

const inputCls = 'w-full min-h-[40px] rounded-lg border border-neutral-300 bg-white px-2 py-1.5 text-[14px] text-[#101311] focus:outline-none focus:ring-2 focus:ring-[#FFD60A]';
const numCls = `${inputCls} text-right tabular-nums`;

function uid(prefix: string): string {
  return `${prefix}-${Date.now().toString(36)}-${Math.floor(Math.random() * 1e6).toString(36)}`;
}

function sourceChip(line: SectionLine) {
  if (line.needsReview) return <span className="inline-block rounded-full bg-amber-100 px-2 py-0.5 text-[10px] font-bold uppercase tracking-wide text-amber-900 ring-1 ring-amber-300">Needs review</span>;
  if (line.source === 'catalog') return <span className="inline-block rounded-full bg-neutral-100 px-2 py-0.5 text-[10px] font-bold uppercase tracking-wide text-neutral-600 ring-1 ring-neutral-200">Catalog</span>;
  if (line.source === 'lookup') return <span className="inline-block rounded-full bg-neutral-100 px-2 py-0.5 text-[10px] font-bold uppercase tracking-wide text-neutral-600 ring-1 ring-neutral-200">Verified lookup</span>;
  return null;
}

export default function EstimatePreviewPage() {
  const [session, setSession] = useState<any>(null);
  const [authReady, setAuthReady] = useState(false);
  const [jobs, setJobs] = useState<any[]>([]);
  const [jobId, setJobId] = useState('');
  const [templateKey, setTemplateKey] = useState(SECTION_TEMPLATES[0].key);
  const [text, setText] = useState('');
  const [sections, setSections] = useState<EstimateSection[]>([]);
  const [collapsed, setCollapsed] = useState<Record<string, boolean>>({});
  const [trace, setTrace] = useState<TracePhase[]>([]);
  const [traceReveal, setTraceReveal] = useState(0);
  const [messages, setMessages] = useState<ChatMsg[]>([
    { role: 'assistant', text: 'Describe the job (or pick a job and a template) and I’ll draft a sectioned estimate from the catalog. Every line stays a draft for office review — nothing is sent to the client.' },
  ]);
  const [chatInput, setChatInput] = useState('');
  const [tab, setTab] = useState<'chat' | 'summary' | 'job' | 'files'>('chat');
  const [generating, setGenerating] = useState(false);
  const [genError, setGenError] = useState('');
  const [apiFlags, setApiFlags] = useState<string[]>([]);
  const [lookupFor, setLookupFor] = useState<string | null>(null);
  const [lookupUrl, setLookupUrl] = useState('');
  const [lookupNote, setLookupNote] = useState('');

  useEffect(() => {
    supabase.auth.getSession().then(async ({ data }) => {
      setSession(data.session);
      setAuthReady(true);
      if (data.session) {
        const { data: rows } = await supabase
          .from('jobs')
          .select('id, request, details, service, status, created_at, clients(name, address)')
          .order('created_at', { ascending: false })
          .limit(100);
        setJobs(rows || []);
      }
    });
  }, []);

  // Reveal the (real) trace steps sequentially so the office can follow the flow.
  useEffect(() => {
    if (!trace.length) { setTraceReveal(0); return; }
    setTraceReveal(0);
    const total = trace.reduce((s, p) => s + p.items.length + 1, 0);
    const t = setInterval(() => setTraceReveal(r => {
      if (r >= total) { clearInterval(t); return r; }
      return r + 1;
    }), 220);
    return () => clearInterval(t);
  }, [trace]);

  const job = jobs.find(j => j.id === jobId);
  const template = SECTION_TEMPLATES.find(t => t.key === templateKey) || SECTION_TEMPLATES[0];

  const result = useMemo(() => priceSectionedEstimate(sections, 13), [sections]);
  const projection = useMemo(() => sectionCustomerProjection(result), [result]);

  function updateLine(sectionId: string, lineId: string, patch: Partial<SectionLine>) {
    setSections(ss => ss.map(s => s.id !== sectionId ? s : {
      ...s,
      lines: s.lines.map(l => {
        if (l.id !== lineId) return l;
        const next = { ...l, ...patch };
        if (patch.laborUnit != null && patch.tierKey == null) {
          // Editing the labour $ directly back-solves hours-per-unit at the current tier.
          const rate = tierRate(next.tierKey);
          next.laborHoursPerUnit = rate > 0 ? Math.round((Number(patch.laborUnit) / rate) * 1000) / 1000 : next.laborHoursPerUnit;
        }
        if (patch.tierKey != null) {
          next.laborUnit = laborUnitFromTier(patch.tierKey, next.laborHoursPerUnit);
        }
        return next;
      }),
    }));
  }

  function addLine(sectionId: string) {
    const line: SectionLine = {
      id: uid('line'), task: '', quantity: 1, unit: 'each', materialCost: null,
      laborUnit: 0, laborHoursPerUnit: 0, tierKey: 'priority', markupPct: 20,
      source: 'placeholder', sourceNote: '', needsReview: true,
      reviewNote: 'New line — enter a material price (or $0 for labour-only) before this estimate can be sent.',
    };
    setSections(ss => ss.map(s => s.id === sectionId ? { ...s, lines: [...s.lines, line] } : s));
  }

  function addSection() {
    const id = uid('section');
    setSections(ss => [...ss, { id, title: 'New section', lines: [] }]);
  }

  async function generate(extraText: string, userEcho?: string) {
    setGenerating(true);
    setGenError('');
    try {
      const { data } = await supabase.auth.getSession();
      if (!data.session) throw new Error('Sign in to continue.');
      const response = await fetch('/api/estimate-sections', {
        method: 'POST',
        headers: { 'content-type': 'application/json', authorization: `Bearer ${data.session.access_token}` },
        body: JSON.stringify({ template_key: templateKey, job_id: jobId || null, text: extraText }),
      });
      const body = await response.json();
      if (!response.ok) throw new Error(body.error || 'Draft generation failed.');
      const newSections = body.sections as EstimateSection[];
      setSections(newSections);
      setCollapsed({});
      setTrace(body.trace as TracePhase[]);
      setApiFlags(body.flags || []);
      const priced = priceSectionedEstimate(newSections, 13);
      const lineCount = newSections.reduce((s, x) => s + x.lines.length, 0);
      const pricedCount = priced.sections.reduce((s, x) => s + x.lines.filter(l => l.lineTotal != null).length, 0);
      const flagCount = priced.flags.length;
      const summary = `Draft ready — ${body.template.name}: ${pricedCount} of ${lineCount} lines priced from the catalog` +
        (flagCount ? `, ${flagCount} flagged for office review` : '') +
        `. Draft total ${money(priced.total ?? 0)} incl. tax, ${priced.estHours}h estimated labour. Nothing is saved or sent — review the lines on the left.`;
      setMessages(ms => [...ms, ...(userEcho ? [{ role: 'user' as const, text: userEcho }] : []), { role: 'assistant' as const, text: summary }]);
      setTab('chat');
    } catch (e) {
      setGenError(e instanceof Error ? e.message : 'Draft generation failed.');
    } finally {
      setGenerating(false);
    }
  }

  async function verifyLookup(sectionId: string, line: SectionLine) {
    setLookupNote('');
    try {
      const { data } = await supabase.auth.getSession();
      if (!data.session) throw new Error('Sign in to continue.');
      const response = await fetch('/api/lookup-price', {
        method: 'POST',
        headers: { 'content-type': 'application/json', authorization: `Bearer ${data.session.access_token}` },
        body: JSON.stringify({ url: lookupUrl }),
      });
      const body = await response.json();
      if (!response.ok) throw new Error(body.error || 'Lookup failed.');
      if (body.cost != null && Number.isFinite(Number(body.cost)) && Number(body.cost) > 0) {
        updateLine(sectionId, line.id, {
          materialCost: Number(body.cost), source: 'lookup', needsReview: false, reviewNote: undefined,
          sourceNote: `Verified from retailer page — ${lookupUrl}`,
        });
        setLookupNote(`Verified supplier price: ${money(body.cost)}.`);
        setLookupFor(null);
      } else {
        setLookupNote(body.note || "Couldn't verify a price — enter it manually.");
      }
    } catch {
      setLookupNote("Couldn't verify a price — enter it manually.");
    }
  }

  if (!authReady) return <main className="mx-auto max-w-3xl px-4 py-16 text-[#101311]"><p role="status">Loading…</p></main>;
  if (!session) {
    return (
      <main className="mx-auto max-w-3xl px-4 py-16 text-[#101311]">
        <Brand />
        <h1 className="mt-6 text-2xl font-bold">Estimate generator — preview</h1>
        <p className="mt-2 text-neutral-600">Sign in with an office account to use the preview.</p>
        <a href="/" className="mt-4 inline-block min-h-[44px] rounded-xl bg-[#101311] px-5 py-3 font-medium text-white">Go to sign in</a>
      </main>
    );
  }

  // Client-summary safety: the Summary tab renders ONLY from the projection.
  const probe = JSON.stringify(projection);
  if (/materialCost|laborUnit|markupPct|supplierCost|sourceNote|tierKey/.test(probe)) {
    throw new Error('Internal pricing data reached the client summary.');
  }

  const photoList = PHOTO_CHECKLISTS[serviceLabel(job?.service || template.serviceLabel)] || [];

  return (
    <main className="min-h-screen bg-[#FAFAF7] text-[#101311]">
      <header className="bg-[#101311] text-white">
        <div className="mx-auto flex max-w-[1400px] flex-wrap items-center gap-4 px-4 py-3">
          <Brand />
          <span className="rounded-full bg-[#FFD60A] px-3 py-1 text-xs font-bold uppercase tracking-widest text-[#101311]">Estimate generator · Preview</span>
          <div className="ml-auto text-right">
            <p className="text-xs uppercase tracking-widest text-neutral-400">Draft total (incl. tax)</p>
            <p className="text-2xl font-bold tabular-nums">{money(result.total ?? 0)}</p>
          </div>
        </div>
      </header>

      <div className="mx-auto max-w-[1400px] px-4 py-4">
        <p className="rounded-xl bg-amber-50 px-4 py-3 text-sm text-amber-900 ring-1 ring-amber-200">
          Preview branch only — drafts are generated from the live catalog but <strong>never saved</strong> to the workspace and never sent to clients. Office review stays mandatory.
        </p>

        {/* Controls */}
        <section aria-label="Draft controls" className="mt-4 rounded-2xl bg-white p-4 shadow-sm ring-1 ring-neutral-200">
          <div className="grid gap-3 md:grid-cols-[1fr_1fr]">
            <div>
              <label htmlFor="pv-job" className="block text-sm font-medium">Job (optional context)</label>
              <select id="pv-job" value={jobId} onChange={e => setJobId(e.target.value)} className="mt-1 w-full min-h-[44px] rounded-xl border border-neutral-300 bg-white px-3 py-2">
                <option value="">No job — free-text description</option>
                {jobs.map(j => <option key={j.id} value={j.id}>{j.clients?.name || 'Client'} · {String(j.request || '').slice(0, 60)}</option>)}
              </select>
            </div>
            <div>
              <label htmlFor="pv-template" className="block text-sm font-medium">Template</label>
              <select id="pv-template" value={templateKey} onChange={e => setTemplateKey(e.target.value)} className="mt-1 w-full min-h-[44px] rounded-xl border border-neutral-300 bg-white px-3 py-2">
                {SECTION_TEMPLATES.map(t => <option key={t.key} value={t.key}>{t.name} — {t.setting}</option>)}
              </select>
            </div>
          </div>
          <label htmlFor="pv-text" className="mt-3 block text-sm font-medium">Job description / notes for the assistant</label>
          <textarea id="pv-text" value={text} onChange={e => setText(e.target.value)} rows={3} className="mt-1 w-full rounded-xl border border-neutral-300 bg-white px-3 py-2" placeholder="e.g. Residential lock change, existing gripset is loose, client wants matte black…" />
          <div className="mt-3 flex flex-wrap items-center gap-3">
            <AsyncButton className="min-h-[44px] rounded-xl bg-[#FFD60A] px-5 font-semibold text-[#101311]" onClick={() => generate(text)}>
              {generating ? 'Drafting…' : 'Draft estimate'}
            </AsyncButton>
            <p className="text-sm text-neutral-500">{template.description}</p>
          </div>
          {genError && <p role="alert" className="mt-2 text-sm text-red-700">{genError}</p>}
        </section>

        {(apiFlags.length > 0 || result.flags.length > 0) && sections.length > 0 && (
          <ul className="mt-4 space-y-2" aria-label="Review flags">
            {[...new Set([...apiFlags, ...result.flags])].map((f, i) => (
              <li key={i} className="flex items-start gap-2 rounded-xl bg-amber-50 px-4 py-2 text-sm text-amber-900 ring-1 ring-amber-200"><Icon name="check" />{f}</li>
            ))}
          </ul>
        )}

        <div className="mt-4 grid gap-4 lg:grid-cols-[1fr_360px]">
          {/* LEFT: sectioned estimate */}
          <div className="space-y-4">
            {sections.length === 0 && (
              <section className="rounded-2xl bg-white p-8 text-center shadow-sm ring-1 ring-neutral-200">
                <h2 className="text-lg font-semibold">No draft yet</h2>
                <p className="mt-1 text-sm text-neutral-600">Pick a template and choose “Draft estimate” — sections, catalog prices and labour are assembled for office review.</p>
              </section>
            )}
            {result.sections.map(section => (
              <section key={section.id} aria-label={section.title} className="overflow-hidden rounded-2xl bg-white shadow-sm ring-1 ring-neutral-200">
                <button type="button" className="flex w-full items-center gap-3 px-4 py-3 text-left" aria-expanded={!collapsed[section.id]} onClick={() => setCollapsed(c => ({ ...c, [section.id]: !c[section.id] }))}>
                  <span className={`inline-block transition-transform ${collapsed[section.id] ? '' : 'rotate-90'}`}><Icon name="chevron" /></span>
                  <span className="text-base font-semibold">{section.title}</span>
                  <span className="ml-auto text-right">
                    <span className="block text-base font-bold tabular-nums">{section.subtotal == null ? '—' : money(section.subtotal)}</span>
                    <span className="block text-xs text-neutral-500">{section.estHours}h estimated labor</span>
                  </span>
                </button>
                {!collapsed[section.id] && (
                  <div className="overflow-x-auto border-t border-neutral-100">
                    <table className="w-full min-w-[760px] text-sm">
                      <thead>
                        <tr className="bg-[#FAFAF7] text-left text-xs uppercase tracking-wide text-neutral-500">
                          <th scope="col" className="px-3 py-2">Task</th>
                          <th scope="col" className="px-3 py-2 text-right">Quantity</th>
                          <th scope="col" className="px-3 py-2 text-right">Material</th>
                          <th scope="col" className="px-3 py-2 text-right">Labor</th>
                          <th scope="col" className="px-3 py-2 text-right">Markup</th>
                          <th scope="col" className="px-3 py-2 text-right">Total</th>
                          <th scope="col" className="px-2 py-2"><span className="sr-only">Actions</span></th>
                        </tr>
                      </thead>
                      <tbody>
                        {section.lines.map(line => {
                          const q = encodeURIComponent(line.task || 'product');
                          return (
                            <tr key={line.id} className="border-t border-neutral-100 align-top">
                              <td className="px-3 py-2">
                                <input aria-label="Task" value={line.task} onChange={e => updateLine(section.id, line.id, { task: e.target.value })} className={`${inputCls} min-w-[180px]`} />
                                <div className="mt-1 flex flex-wrap items-center gap-2">
                                  {sourceChip(line)}
                                  {line.sourceNote && <span className="text-[11px] text-neutral-500" title={line.sourceNote}>{line.source === 'catalog' ? 'Catalog match' : ''}</span>}
                                  {line.materialCost == null && (
                                    <button type="button" className="inline-flex min-h-[32px] items-center gap-1 rounded-lg px-2 text-xs font-medium ring-1 ring-neutral-300" onClick={() => { setLookupFor(lookupFor === line.id ? null : line.id); setLookupUrl(''); setLookupNote(''); }}>
                                      <Icon name="search" /> Look up price
                                    </button>
                                  )}
                                </div>
                                {line.reviewNote && <p className="mt-1 text-xs text-amber-800">{line.reviewNote}</p>}
                                {line.note && <p className="mt-1 text-xs text-neutral-500">{line.note}</p>}
                                {lookupFor === line.id && (
                                  <div className="mt-2 rounded-xl bg-[#FAFAF7] p-3 ring-1 ring-neutral-200">
                                    <p className="text-xs font-semibold">Check supplier price</p>
                                    <div className="mt-1 flex flex-wrap gap-2 text-sm">
                                      <a href={`https://www.homedepot.ca/search?q=${q}`} target="_blank" rel="noopener" className="inline-flex min-h-[36px] items-center rounded-lg bg-[#FFD60A] px-3 font-medium text-[#101311]">Home Depot Canada</a>
                                      <a href={`https://www.amazon.ca/s?k=${q}`} target="_blank" rel="noopener" className="inline-flex min-h-[36px] items-center rounded-lg bg-[#FFD60A] px-3 font-medium text-[#101311]">Amazon Canada</a>
                                    </div>
                                    <label className="mt-2 block text-xs font-medium" htmlFor={`lk-${line.id}`}>Paste product URL</label>
                                    <div className="mt-1 flex gap-2">
                                      <input id={`lk-${line.id}`} value={lookupUrl} onChange={e => setLookupUrl(e.target.value)} placeholder="https://www.homedepot.ca/…" className={inputCls} />
                                      <AsyncButton className="min-h-[40px] shrink-0 rounded-xl bg-[#101311] px-4 font-medium text-white" onClick={() => verifyLookup(section.id, line)}>Verify &amp; fill</AsyncButton>
                                    </div>
                                    {lookupNote && <p aria-live="polite" className="mt-1 text-xs text-neutral-700">{lookupNote}</p>}
                                  </div>
                                )}
                              </td>
                              <td className="px-3 py-2">
                                <input aria-label="Quantity" type="number" min="0" step="any" value={line.quantity} onChange={e => updateLine(section.id, line.id, { quantity: Number(e.target.value) })} className={`${numCls} w-20`} />
                                <input aria-label="Unit" value={line.unit} onChange={e => updateLine(section.id, line.id, { unit: e.target.value })} className={`${inputCls} mt-1 w-20 text-xs`} />
                              </td>
                              <td className="px-3 py-2">
                                <input aria-label="Material unit cost (internal)" type="number" min="0" step="0.01" value={line.materialCost ?? ''} placeholder="—" onChange={e => updateLine(section.id, line.id, { materialCost: e.target.value === '' ? null : Number(e.target.value), needsReview: e.target.value === '' ? line.needsReview : false, reviewNote: e.target.value === '' ? line.reviewNote : undefined, source: e.target.value === '' ? line.source : 'manual' })} className={`${numCls} w-24`} />
                                <span className="mt-1 block text-[10px] uppercase tracking-wide text-neutral-400">cost · internal</span>
                              </td>
                              <td className="px-3 py-2">
                                <input aria-label="Labor unit cost (internal)" type="number" min="0" step="0.01" value={line.laborUnit} onChange={e => updateLine(section.id, line.id, { laborUnit: Number(e.target.value) })} className={`${numCls} w-24`} />
                                <select aria-label="Labor tier" value={line.tierKey} onChange={e => updateLine(section.id, line.id, { tierKey: e.target.value as LaborTierKey })} className="mt-1 w-24 rounded-lg border border-neutral-300 bg-white px-1 py-1 text-[11px]">
                                  {LABOR_TIERS.map(t => <option key={t.key} value={t.key}>${t.rate}/hr</option>)}
                                </select>
                              </td>
                              <td className="px-3 py-2">
                                <div className="flex items-center justify-end gap-1">
                                  <input aria-label="Markup percent" type="number" min="0" step="1" value={line.markupPct} onChange={e => updateLine(section.id, line.id, { markupPct: Number(e.target.value) })} className={`${numCls} w-[74px]`} />
                                  <span className="text-neutral-500">%</span>
                                </div>
                              </td>
                              <td className="px-3 py-2 text-right font-semibold tabular-nums">{line.lineTotal == null ? '—' : money(line.lineTotal)}</td>
                              <td className="px-2 py-2">
                                <button type="button" aria-label={`Remove ${line.task || 'line'}`} onClick={() => setSections(ss => ss.map(s => s.id === section.id ? { ...s, lines: s.lines.filter(l => l.id !== line.id) } : s))} className="min-h-[40px] min-w-[40px] rounded-xl ring-1 ring-neutral-300"><Icon name="minus" /></button>
                              </td>
                            </tr>
                          );
                        })}
                      </tbody>
                    </table>
                    <div className="flex flex-wrap gap-2 px-3 py-3">
                      <button type="button" onClick={() => addLine(section.id)} className="inline-flex min-h-[40px] items-center gap-2 rounded-xl px-3 font-medium ring-1 ring-neutral-300"><Icon name="plus" /> Add line</button>
                    </div>
                  </div>
                )}
              </section>
            ))}
            {sections.length > 0 && (
              <>
                <button type="button" onClick={addSection} className="inline-flex min-h-[40px] items-center gap-2 rounded-xl bg-white px-4 font-medium ring-1 ring-neutral-300"><Icon name="plus" /> Add section</button>
                <section aria-label="Totals" className="rounded-2xl bg-white p-5 shadow-sm ring-1 ring-neutral-200">
                  <dl className="space-y-1 text-sm">
                    <div className="flex justify-between"><dt>Subtotal</dt><dd className="tabular-nums">{money(result.subtotal ?? 0)}</dd></div>
                    <div className="flex justify-between"><dt>Tax (13%)</dt><dd className="tabular-nums">{money(result.tax ?? 0)}</dd></div>
                    <div className="flex justify-between text-lg font-bold"><dt>Total</dt><dd className="tabular-nums">{money(result.total ?? 0)}</dd></div>
                    <div className="flex justify-between text-neutral-600"><dt>Estimated labour</dt><dd className="tabular-nums">{result.estHours}h</dd></div>
                  </dl>
                  <button type="button" disabled className="mt-4 min-h-[48px] w-full rounded-xl bg-neutral-200 font-semibold text-neutral-500" title="Saving is disabled in this preview — nothing is written to the live workspace.">
                    Save estimate as draft (disabled in preview)
                  </button>
                  <p className="mt-2 text-xs text-neutral-500">When merged, saving will create a DRAFT estimate behind the mandatory office review gate — exactly like the current builder.</p>
                </section>
              </>
            )}
          </div>

          {/* RIGHT RAIL */}
          <aside className="overflow-hidden rounded-2xl bg-white shadow-sm ring-1 ring-neutral-200 lg:sticky lg:top-4 lg:self-start">
            <div className="flex border-b border-neutral-200" role="tablist" aria-label="Assistant panel">
              {(['chat', 'summary', 'job', 'files'] as const).map(t => (
                <button key={t} role="tab" aria-selected={tab === t} onClick={() => setTab(t)} className={`min-h-[44px] flex-1 px-2 text-sm font-semibold capitalize ${tab === t ? 'bg-[#101311] text-white' : 'text-neutral-600 hover:bg-[#FAFAF7]'}`}>
                  {t === 'job' ? 'Job' : t}
                </button>
              ))}
              <span className="hidden items-center px-3 text-xs font-bold uppercase tracking-widest text-neutral-400 sm:flex">Assistant</span>
            </div>

            {tab === 'chat' && (
              <div className="flex max-h-[720px] flex-col">
                <div className="flex-1 space-y-3 overflow-y-auto p-4">
                  {messages.map((m, i) => (
                    <div key={i} className={`max-w-[92%] rounded-2xl px-3 py-2 text-sm ${m.role === 'user' ? 'ml-auto bg-[#101311] text-white' : 'bg-[#FAFAF7] ring-1 ring-neutral-200'}`}>{m.text}</div>
                  ))}
                  {trace.length > 0 && (
                    <div className="rounded-2xl bg-[#FAFAF7] p-3 ring-1 ring-neutral-200" aria-label="Draft trace">
                      {(() => {
                        let seen = 0;
                        return trace.map(phase => {
                          const headerVisible = traceReveal > seen; seen += 1;
                          const items = phase.items.map(item => {
                            const visible = traceReveal > seen; seen += 1;
                            return { item, visible };
                          });
                          if (!headerVisible) return null;
                          return (
                            <div key={phase.id} className="mb-3 last:mb-0">
                              <p className="flex items-center gap-2 text-sm font-semibold"><span className="text-[#101311]">✦</span>{phase.label}<span className="ml-auto text-xs font-normal text-neutral-400">{(phase.ms / 1000).toFixed(1)}s</span></p>
                              <ul className="mt-1 space-y-1">
                                {items.filter(x => x.visible).map((x, i) => (
                                  <li key={i} className="flex items-start gap-2 text-[13px] text-neutral-700">
                                    <span className={x.item.ok ? 'text-emerald-600' : 'text-amber-500'}><Icon name={x.item.ok ? 'check' : 'clock'} /></span>
                                    <span><strong className="font-medium">{x.item.label}</strong><span className="block text-xs text-neutral-500">{x.item.detail}</span></span>
                                  </li>
                                ))}
                              </ul>
                            </div>
                          );
                        });
                      })()}
                    </div>
                  )}
                  <p className="text-[11px] text-neutral-400">The assistant drafts from the catalog and the existing pricing engine. It can make mistakes — the office double-checks every line before anything reaches a client.</p>
                </div>
                <form className="border-t border-neutral-200 p-3" onSubmit={e => { e.preventDefault(); const v = chatInput.trim(); if (!v || generating) return; setChatInput(''); setText(v); generate(v, v); }}>
                  <label className="sr-only" htmlFor="pv-chat">Message the assistant</label>
                  <div className="flex gap-2">
                    <input id="pv-chat" value={chatInput} onChange={e => setChatInput(e.target.value)} placeholder="Type a message…" className="min-h-[44px] flex-1 rounded-xl border border-neutral-300 px-3" />
                    <button type="submit" disabled={generating} className="min-h-[44px] rounded-xl bg-[#FFD60A] px-4 font-semibold text-[#101311]">Draft</button>
                  </div>
                </form>
              </div>
            )}

            {tab === 'summary' && (
              <div className="max-h-[720px] overflow-y-auto p-4" aria-label="Client summary">
                <p className="text-xs font-bold uppercase tracking-widest text-neutral-500">Client view — internal costs &amp; markup hidden</p>
                {projection.sections.length === 0 && <p className="mt-3 text-sm text-neutral-600">Draft an estimate to see the client summary.</p>}
                {projection.sections.map((s, i) => (
                  <div key={i} className="mt-4">
                    <div className="flex items-baseline justify-between gap-2">
                      <h3 className="font-semibold">{s.title}</h3>
                      <span className="font-semibold tabular-nums">{money(s.subtotal)}</span>
                    </div>
                    <ul className="mt-1 divide-y divide-neutral-100 text-sm">
                      {s.lines.map((l, j) => (
                        <li key={j} className="flex justify-between gap-2 py-1.5">
                          <span>{l.task}<span className="block text-xs text-neutral-500">{l.quantity} {l.unit}</span></span>
                          <span className="tabular-nums">{money(l.lineTotal)}</span>
                        </li>
                      ))}
                    </ul>
                  </div>
                ))}
                {projection.sections.length > 0 && (
                  <dl className="mt-4 space-y-1 border-t border-neutral-200 pt-3 text-sm">
                    <div className="flex justify-between"><dt>Subtotal</dt><dd className="tabular-nums">{money(projection.subtotal ?? 0)}</dd></div>
                    <div className="flex justify-between"><dt>Tax ({projection.taxPct}%)</dt><dd className="tabular-nums">{money(projection.tax ?? 0)}</dd></div>
                    <div className="flex justify-between text-base font-bold"><dt>Total</dt><dd className="tabular-nums">{money(projection.total ?? 0)}</dd></div>
                    <div className="flex justify-between text-neutral-600"><dt>Estimated labour</dt><dd>{projection.estHours}h</dd></div>
                  </dl>
                )}
                {!projection.complete && projection.sections.length > 0 && <p className="mt-2 text-xs text-neutral-500">Draft — some lines are still being priced.</p>}
              </div>
            )}

            {tab === 'job' && (
              <div className="max-h-[720px] overflow-y-auto p-4" aria-label="Job context">
                {!job && <p className="text-sm text-neutral-600">No job selected — the draft is using the free-text description only.</p>}
                {job && (
                  <dl className="space-y-2 text-sm">
                    <div><dt className="text-xs font-bold uppercase tracking-widest text-neutral-500">Client</dt><dd className="font-medium">{job.clients?.name || 'Client'}</dd></div>
                    <div><dt className="text-xs font-bold uppercase tracking-widest text-neutral-500">Request</dt><dd>{job.request}</dd></div>
                    {job.details && <div><dt className="text-xs font-bold uppercase tracking-widest text-neutral-500">Details</dt><dd className="whitespace-pre-wrap">{job.details}</dd></div>}
                    <div><dt className="text-xs font-bold uppercase tracking-widest text-neutral-500">Service</dt><dd>{serviceLabel(job.service || '')}</dd></div>
                    <div><dt className="text-xs font-bold uppercase tracking-widest text-neutral-500">Status</dt><dd className="capitalize">{String(job.status || '').replaceAll('_', ' ')}</dd></div>
                    {job.clients?.address && <div><dt className="text-xs font-bold uppercase tracking-widest text-neutral-500">Address</dt><dd>{job.clients.address}</dd></div>}
                    <a href={`/job-report/${job.id}`} className="mt-2 inline-flex min-h-[44px] items-center rounded-xl bg-[#101311] px-4 font-medium text-white">Open job report ↗</a>
                  </dl>
                )}
              </div>
            )}

            {tab === 'files' && (
              <div className="max-h-[720px] overflow-y-auto p-4" aria-label="Files and photo checklist">
                <p className="text-xs font-bold uppercase tracking-widest text-neutral-500">Photo checklist — {serviceLabel(job?.service || template.serviceLabel)}</p>
                {photoList.length ? (
                  <ul className="mt-2 space-y-1 text-sm">{photoList.map(p => <li key={p} className="flex items-center gap-2"><Icon name="photo" />{p}</li>)}</ul>
                ) : <p className="mt-2 text-sm text-neutral-600">No checklist for this service.</p>}
                <p className="mt-3 text-sm text-neutral-600">Job photos and files live in the job thread — see the <strong>Job report</strong> for the full gallery and file folders{job ? <> (<a className="font-medium underline" href={`/job-report/${job.id}`}>open report</a>)</> : ''}.</p>
              </div>
            )}
          </aside>
        </div>

        <p className="mt-4 text-xs text-neutral-500">Section math: line total = quantity × (material + labor) × (1 + markup). Material/labor columns are internal costs — the Summary tab is the only client-safe view. Labour $ derives from the shared tier table ($150 / $180 / $220 per hr); templates default to the $180 standard working tier.</p>
      </div>
    </main>
  );
}
